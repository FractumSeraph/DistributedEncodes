#!/usr/bin/env python3
"""Generate the two fallback headers for the wasm-SIMD build of SVT-AV1 2.3.0.

Usage: gen_fallbacks.py <SVT-AV1 dir> <libSvtAv1Enc.a from a first build> <nm>

Hand-written x86 assembly (.asm) cannot be compiled for WebAssembly, so every
function that lives only in assembly, and every intrinsics wrapper that calls
into assembly, has to be steered to another implementation:

  wasm_simd_asm_fallbacks.h   force-included everywhere. Functions that exist
                              ONLY in assembly and have a C twin are renamed to
                              that twin.
  wasm_simd_rtcd_fallbacks.h  included by the two run-time dispatch files.
                              Intrinsics wrappers that call assembly helpers
                              are replaced, in the dispatch tables only, by a
                              non-assembly implementation.

Assembly helpers left without any caller after that stay undefined; the final
link allows exactly that list (written to wasm_simd_allowed_undefined.txt).
"""
import sys, os, re, subprocess

svt, lib, nm = sys.argv[1:4]
codec = os.path.join(svt, 'Source/Lib/Codec')

# ---- symbols per object ------------------------------------------------------
out = subprocess.run([nm, lib], capture_output=True, text=True).stdout
defined, undefined, by_obj = set(), {}, {}
obj = None
for line in out.splitlines():
    if line.endswith(':'):
        obj = line[:-1]; by_obj[obj] = set(); continue
    parts = line.split()
    if len(parts) >= 2 and parts[-2] in ('T', 't', 'W'):
        defined.add(parts[-1]); by_obj[obj].add(parts[-1])
    elif len(parts) >= 2 and parts[-2] == 'U':
        undefined.setdefault(parts[-1], set()).add(obj)
asm_only = sorted(s for s in undefined if s not in defined and
                  re.match(r'(svt_|Log2f_ASM|RunEmms)', s))

rtcd_text = ''.join(open(os.path.join(codec, f), encoding='utf-8').read()
                    for f in ('common_dsp_rtcd.c', 'aom_dsp_rtcd.c'))
rtcd_tokens = set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', rtcd_text))

ISA = r'_(sse2|ssse3|sse4_1|avx2|sse|sse3|avx|sse2_intrin|ssse3_intrin|sse4_1_intrin|avx2_intrin)$'

def c_twin(sym):
    m = re.search(ISA, sym)
    if not m:
        return None
    twin = sym[:m.start()] + '_c'
    return twin if twin in defined else None

# ---- 1. pure-assembly functions with a C twin: rename everywhere ------------
asm_fb, helpers = [], []
for s in asm_only:
    t = c_twin(s)
    if t:
        asm_fb.append((s, t))
    elif s not in ('Log2f_ASM', 'RunEmms'):
        helpers.append(s)

# ---- 2. dispatch-table replacements ------------------------------------------
rtcd_fb = {'Log2f_ASM': 'svt_aom_log2f_32'}
# AVX2 intrinsics code that compiles but gives a different result under
# Emscripten's 256-bit emulation (found by bisecting all 542 AVX2 entries
# against the C build's output). With this one on, the bitstream is corrupt.
rtcd_fb['svt_copy_mi_map_grid_avx2'] = 'svt_copy_mi_map_grid_c'

def best(sym, prefer=()):
    m = re.search(ISA, sym)
    base = sym[:m.start()]
    for suf in prefer:
        if base + suf in defined and base + suf not in tainted:
            return base + suf
    return base + '_c' if base + '_c' in defined else None

# Objects whose exported wrappers call assembly helpers. None = every exported
# symbol used in a dispatch table; otherwise only names matching the pattern.
wrapper_objs = {
    'highbd_variance_sse2.c.o': None,
    'variance_impl_ssse3.c.o': None,
    'variance_sse2.c.o': r'sub_pixel',
    'aom_subpixel_8t_intrin_ssse3.c.o': None,
    # aom_subpixel_8t_intrin_avx2.c.o is NOT listed: its assembly helpers are
    # provided in C by wasm_simd_asm_helpers.c, so the AVX2 convolve is usable.
    'blend_a64_mask_avx2.c.o': r'^svt_av1(_highbd)?_blend_a64_[hv]mask(_16bit)?_avx2$',
}
tainted = set()
for o, pat in wrapper_objs.items():
    for s in by_obj.get(o, ()):
        if s in rtcd_tokens and re.search(ISA, s) and (pat is None or re.search(pat, s)):
            tainted.add(s)
missing = []
for s in sorted(tainted):
    t = best(s, ('_sse4_1',) if s.endswith('_avx2') else ())
    if not t and s.startswith('svt_av1_'):      # same function, older prefix
        t = best('svt_aom_' + s[len('svt_av1_'):], ('_sse4_1',))
    if t:
        rtcd_fb[s] = t
    else:
        missing.append(s)

# dav1d assembly front ends -> SVT's own intrinsics
for s in sorted(t for t in rtcd_tokens if 'dav1d' in t and t.endswith('_avx2')):
    alt = s.replace('svt_dav1d_', 'svt_av1_')
    if alt in defined:
        rtcd_fb[s] = alt
    else:
        t = best(alt, ('_sse4_1',))
        if t: rtcd_fb[s] = t
        else: missing.append(s)

def write(name, intro, pairs):
    guard = name.upper().replace('.', '_')
    with open(os.path.join(codec, name), 'w', encoding='utf-8') as f:
        f.write(f"/* Generated by gen_fallbacks.py for the wasm-SIMD build. */\n#ifndef {guard}\n#define {guard}\n")
        if name == 'wasm_simd_asm_fallbacks.h':
            f.write('#include "wasm_simd_intrinsics.h"\n')
        f.write("#ifdef SVT_WASM_SIMD\n" + intro)
        for a, b in pairs:
            f.write(f"#define {a} {b}\n")
        f.write("#endif\n#endif\n")

write('wasm_simd_asm_fallbacks.h',
      "/* Functions that exist only as x86 assembly: use the C version. */\n", asm_fb)
write('wasm_simd_rtcd_fallbacks.h',
      "/* Dispatch-table entries whose implementation calls x86 assembly. */\n",
      sorted(rtcd_fb.items()))
with open(os.path.join(svt, 'wasm_simd_allowed_undefined.txt'), 'w') as f:
    f.write('\n'.join(helpers) + '\n')

print(f"asm-only renamed to C: {len(asm_fb)}; dispatch replacements: {len(rtcd_fb)}; "
      f"assembly helpers left undefined: {len(helpers)}")
for s in missing:
    print("  NO REPLACEMENT FOUND:", s)
